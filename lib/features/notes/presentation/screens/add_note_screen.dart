import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:go_router/go_router.dart';

import '../../../../core/constants/app_spacing.dart';
import '../../../../core/l10n/build_context_l10n_extension.dart';
import '../../../../core/theme/app_theme.dart';
import '../../domain/note_item.dart';
import '../../data/notes_repository.dart';
import '../../../auth/presentation/auth_providers.dart';

/// Screen for adding a new note
/// 
/// Features:
/// - Title field (optional)
/// - Content text field
/// - Type selection (shared, private, bucketList, secretGift)
/// - Save button with loading state
class AddNoteScreen extends ConsumerStatefulWidget {
  const AddNoteScreen({super.key, this.initialType});

  final NoteType? initialType;

  @override
  ConsumerState<AddNoteScreen> createState() => _AddNoteScreenState();
}

class _AddNoteScreenState extends ConsumerState<AddNoteScreen> {
  final _formKey = GlobalKey<FormState>();
  final _titleController = TextEditingController();
  final _contentController = TextEditingController();
  
  late NoteType _selectedType;
  
  @override
  void initState() {
    super.initState();
    _selectedType = widget.initialType ?? NoteType.shared;
  }
  bool _isSaving = false;

  @override
  void dispose() {
    _titleController.dispose();
    _contentController.dispose();
    super.dispose();
  }

  Future<void> _saveNote() async {
    if (!_formKey.currentState!.validate()) {
      return;
    }

    final content = _contentController.text.trim();
    if (content.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(context.l10n.addNoteScreenContentEmptyError),
          backgroundColor: context.colors.love,
          behavior: SnackBarBehavior.floating,
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(12),
          ),
        ),
      );
      return;
    }

    setState(() {
      _isSaving = true;
    });

    try {
      final currentUserAsync = ref.read(currentUserDataProvider);
      final coupleAsync = ref.read(currentCoupleProvider);
      
      final currentUser = currentUserAsync.valueOrNull;
      final couple = coupleAsync.valueOrNull;
      
      if (currentUser == null) {
        throw Exception(context.l10n.addNoteScreenNotAuthenticatedError);
      }

      if (couple == null || couple.id.isEmpty) {
        throw Exception(context.l10n.addNoteScreenNotPairedError);
      }

      final note = NoteItem(
        id: '', // Will be generated by repository
        content: content,
        title: _titleController.text.trim().isEmpty 
            ? null 
            : _titleController.text.trim(),
        type: _selectedType,
        authorId: currentUser.uid,
        createdAt: DateTime.now(),
      );

      final repository = ref.read(notesRepositoryProvider);
      await repository.createNote(
        note: note,
        coupleId: couple.id,
      );

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(context.l10n.addNoteScreenSaveSuccess),
            backgroundColor: context.colors.success,
            behavior: SnackBarBehavior.floating,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(12),
            ),
            duration: const Duration(seconds: 2),
          ),
        );
        context.pop();
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(context.l10n.addNoteScreenSaveError(e.toString())),
            backgroundColor: context.colors.love,
            behavior: SnackBarBehavior.floating,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(12),
            ),
            duration: const Duration(seconds: 3),
          ),
        );
      }
    } finally {
      if (mounted) {
        setState(() {
          _isSaving = false;
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: context.colors.background,
      appBar: AppBar(
        title: Text(context.l10n.addNoteScreenTitle),
        actions: [
          if (_isSaving)
            const Padding(
              padding: EdgeInsets.all(AppSpacing.md),
              child: Center(
                child: SizedBox(
                  width: 20,
                  height: 20,
                  child: CircularProgressIndicator(
                    strokeWidth: 2,
                    valueColor: AlwaysStoppedAnimation<Color>(Colors.white),
                  ),
                ),
              ),
            )
          else
            TextButton(
              onPressed: _saveNote,
              child: Text(
                context.l10n.commonSave,
                style: TextStyle(
                  color: context.colors.primary,
                  fontWeight: FontWeight.w700,
                ),
              ),
            ),
        ],
      ),
      body: SafeArea(
        child: Form(
          key: _formKey,
          child: SingleChildScrollView(
            padding: const EdgeInsets.all(AppSpacing.lg),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                // Title field (optional)
                TextFormField(
                  controller: _titleController,
                  decoration: InputDecoration(
                    labelText: context.l10n.addNoteScreenTitleLabel,
                    hintText: context.l10n.addNoteScreenTitleHint,
                    border: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(16),
                      borderSide: BorderSide(
                        color: context.colors.textSecondary.withOpacity(0.2),
                      ),
                    ),
                    enabledBorder: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(16),
                      borderSide: BorderSide(
                        color: context.colors.textSecondary.withOpacity(0.2),
                      ),
                    ),
                    focusedBorder: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(16),
                      borderSide: BorderSide(
                        color: context.colors.primary,
                        width: 2,
                      ),
                    ),
                    filled: true,
                    fillColor: context.colors.card,
                    contentPadding: const EdgeInsets.all(AppSpacing.md),
                  ),
                  style: Theme.of(context).textTheme.bodyLarge?.copyWith(
                        color: context.colors.text,
                      ),
                ),
                const SizedBox(height: AppSpacing.lg),

                // Content field
                TextFormField(
                  controller: _contentController,
                  decoration: InputDecoration(
                    labelText: context.l10n.addNoteScreenContentLabel,
                    hintText: context.l10n.addNoteScreenContentHint,
                    border: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(16),
                      borderSide: BorderSide(
                        color: context.colors.textSecondary.withOpacity(0.2),
                      ),
                    ),
                    enabledBorder: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(16),
                      borderSide: BorderSide(
                        color: context.colors.textSecondary.withOpacity(0.2),
                      ),
                    ),
                    focusedBorder: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(16),
                      borderSide: BorderSide(
                        color: context.colors.primary,
                        width: 2,
                      ),
                    ),
                    filled: true,
                    fillColor: context.colors.card,
                    contentPadding: const EdgeInsets.all(AppSpacing.md),
                  ),
                  maxLines: 8,
                  style: Theme.of(context).textTheme.bodyLarge?.copyWith(
                        color: context.colors.text,
                      ),
                  validator: (value) {
                    if (value == null || value.trim().isEmpty) {
                      return context.l10n.addNoteScreenContentRequired;
                    }
                    return null;
                  },
                ),
                const SizedBox(height: AppSpacing.lg),

                // Type selection
                Text(
                  context.l10n.addNoteScreenTypeLabel,
                  style: Theme.of(context).textTheme.titleMedium?.copyWith(
                        fontWeight: FontWeight.w700,
                        color: context.colors.text,
                      ),
                ),
                const SizedBox(height: AppSpacing.sm),
                Wrap(
                  spacing: AppSpacing.sm,
                  runSpacing: AppSpacing.sm,
                  children: NoteType.values.map((type) {
                    final isSelected = _selectedType == type;
                    return ChoiceChip(
                      label: Text(_getTypeLabel(type)),
                      selected: isSelected,
                      onSelected: (selected) {
                        if (selected) {
                          setState(() {
                            _selectedType = type;
                          });
                        }
                      },
                      selectedColor: context.colors.primary.withOpacity(0.2),
                      backgroundColor: context.colors.background,
                      labelStyle: TextStyle(
                        color: isSelected
                            ? context.colors.primary
                            : context.colors.text,
                        fontWeight: isSelected
                            ? FontWeight.w700
                            : FontWeight.w400,
                      ),
                      side: BorderSide(
                        color: isSelected
                            ? context.colors.primary
                            : context.colors.textSecondary.withOpacity(0.3),
                        width: isSelected ? 2 : 1,
                      ),
                    );
                  }).toList(),
                ),
                const SizedBox(height: AppSpacing.xl),

                // Save button
                ElevatedButton(
                  onPressed: _isSaving ? null : _saveNote,
                  style: ElevatedButton.styleFrom(
                    backgroundColor: context.colors.primary,
                    foregroundColor: Colors.white,
                    padding: const EdgeInsets.symmetric(
                      vertical: AppSpacing.md,
                    ),
                    shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(16),
                    ),
                    elevation: 0,
                  ),
                  child: _isSaving
                      ? const SizedBox(
                          height: 20,
                          width: 20,
                          child: CircularProgressIndicator(
                            strokeWidth: 2,
                            valueColor: AlwaysStoppedAnimation<Color>(Colors.white),
                          ),
                        )
                      : Text(
                          context.l10n.addNoteScreenSaveNoteButton,
                          style: const TextStyle(
                            fontWeight: FontWeight.w700,
                            fontSize: 16,
                          ),
                        ),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }

  String _getTypeLabel(NoteType type) {
    switch (type) {
      case NoteType.shared:
        return context.l10n.addNoteScreenTypeShared;
      case NoteType.private:
        return context.l10n.addNoteScreenTypePrivate;
      case NoteType.bucketList:
        return context.l10n.addNoteScreenTypeBucketList;
      case NoteType.secretGift:
        return context.l10n.addNoteScreenTypeSecretGift;
    }
  }
}
